'use strict';
const mongoose = require('mongoose');
const defineModel = require('./define-model');

const { Mixed } = mongoose.Schema.Types;

/**
 * Accreditation indicators (Mongo "primary" connection, collection `indicadoresacreditacion`). Stored keys are legacy names.
 * One document per program and year. Version 2 keeps every legacy field and adds the complete detail
 * (summary, types, institutions, tutors, advisors and the practice-by-practice roster) so that an
 * accreditation file can be built from this collection alone, without going back to PostgreSQL.
 * New fields are optional so that documents generated by the first version are still readable.
 */
const schema = new mongoose.Schema({
  anio: { type: Number, required: true },
  idPrograma: { type: String, required: true }, // varchar(30) in PostgreSQL
  nombrePrograma: { type: String, required: true },
  facultadPrograma: { type: String, required: false },
  totalEstudiantes: { type: Number, required: false },
  totalEstudiantesActivos: { type: Number, required: true },
  totalTutoresActivos: { type: Number, required: false },
  resumenPracticas: { type: Mixed, required: false }, // { total, activas, finalizadas, notaPromedio, tasaAprobacion, horasRegistradas ... }
  practicasPorTipo: { type: [Mixed], required: true }, // [{ idTipo, tipo, semestre, horasRequeridas, cantidad, estudiantes, promedioNota, porcentajeAprobacion }]
  distribucionNotas: { type: [Mixed], required: true }, // [{ rango, cantidadEstudiantes }]
  acompanamientoDocente: { type: Mixed, required: true }, // { retroalimentacionesTutor, retroalimentacionesAsesor, practicasSinRetroTutor ... }
  entidadesVinculadas: { type: [Mixed], required: true }, // [{ nit, nombreEntidad, direccion, encargado, correo, cantidadPracticas ... }]
  tutores: { type: [Mixed], required: false }, // [{ documento, nombre, correo, practicas, estudiantes, retroalimentaciones, promedioNota }]
  asesores: { type: [Mixed], required: false },
  detallePracticas: { type: [Mixed], required: false }, // one entry per practice of the program in the year
  tasaDesercion: { type: Number, required: true }, // percentage, e.g. 12.5
  duracionPromedioPracticasDias: { type: Number, required: true },
  fechaGeneracion: { type: Date, required: false },
  versionIndicador: { type: Number, required: false },
  observaciones: { type: String, required: false }
});

schema.index({ anio: 1, idPrograma: 1 });

module.exports = defineModel('primary', 'IndicadorAcreditacion', schema, 'indicadoresacreditacion');
